// Laya decision client — zero-dependency typed decisions over HTTP.
// Calls the laptop's Laya service (installed via laya-service/install.sh).
// Laya is a System 1 model: state + typed questions in, calibrated probabilities out.
// Never generates text, so there is no JSON to parse/truncate (unlike LM Studio brain).
const { loadConfig } = require('./config');

const VERIFY_QUESTIONS = {
  faithful: {
    type: 'noul',
    instructions: 'Does the REWRITTEN text faithfully preserve the meaning and facts of the ORIGINAL — same claims, numbers, names and dates, nothing invented, no contradictions?',
  },
  hallucination: {
    type: 'noul',
    instructions: 'Does the REWRITTEN text invent facts, numbers, names, dates, or claims that are NOT present in the ORIGINAL?',
  },
  meta: {
    type: 'noul',
    instructions: 'Does the REWRITTEN text contain meta-text, chat-reply language, reasoning, code, JSON, or an explanation of how it was written, instead of pure prose?',
  },
};

const JUDGE_QUESTION = {
  human: {
    type: 'noul',
    instructions: 'Does this text sound like it was written by a real human being rather than generated by an AI?',
  },
};

const BACKFIRE_QUESTION = {
  improvement: {
    type: 'noul',
    instructions: 'Compared to the PREVIOUS version, is the REWRITTEN text noticeably more natural and human-sounding (fewer AI patterns), not just cosmetically different?',
  },
};

let layaCache = { ok: null, checkedAt: 0 };

function layaUrl(cfg) {
  return process.env.LAYA_URL || (cfg && cfg.layaUrl) || 'http://192.168.29.233:8094';
}

function layaToken(cfg) {
  return process.env.LAYA_TOKEN || (cfg && cfg.layaToken) || '';
}

function authHeaders(cfg) {
  const tok = layaToken(cfg);
  return tok ? { Authorization: 'Bearer ' + tok } : {};
}

function resetLayaCache() {
  layaCache = { ok: null, checkedAt: 0 };
}

// Direct health probe usable with an arbitrary URL+token (e.g. the /layacfg handshake).
async function checkLayaHealth(opts = {}) {
  const url = (opts.url || layaUrl(loadConfig())).replace(/\/+$/, '');
  const token = opts.token !== undefined ? opts.token : layaToken(loadConfig());
  const timeoutMs = opts.timeoutMs || loadConfig().layaTimeoutMs || 15000;
  try {
    const ctrl = new AbortController();
    const t = setTimeout(() => ctrl.abort(), timeoutMs);
    const headers = token ? { Authorization: 'Bearer ' + token } : {};
    const res = await fetch(url + '/health', { signal: ctrl.signal, headers }).finally(() => clearTimeout(t));
    const text = await res.text().catch(() => '');
    if (!res.ok) return { ok: false, error: `HTTP ${res.status}: ${text.slice(0, 200)}` };
    const body = JSON.parse(text);
    return { ok: true, device: body.device, routing: body.routing };
  } catch (e) {
    return { ok: false, error: e.message };
  }
}

async function isLayaReachable() {
  const cfg = loadConfig();
  const now = Date.now();
  if (cfg.layaEnabled === false) {
    layaCache = { ok: false, checkedAt: now };
    return false;
  }
  if (layaCache.ok !== null && now - layaCache.checkedAt < 30000) return layaCache.ok;
  const r = await checkLayaHealth();
  layaCache = { ok: r.ok, checkedAt: now };
  return r.ok;
}

// Keep state inside Laya's token budget (~320 tokens English root, ~768 typed-decisions).
// Roughly 3.5 chars/token for English; cap at 1400 chars per side.
function truncateForState(str, limit) {
  str = String(str || '');
  return str.length > limit ? str.slice(0, limit) : str;
}

async function layaDecide(state, questions, opts = {}) {
  const cfg = loadConfig();
  const timeout = opts.timeoutMs || (cfg && cfg.layaTimeoutMs) || 15000;
  const payload = { state, questions };
  if (opts.model) payload.model = opts.model;
  const ctrl = new AbortController();
  const t = setTimeout(() => ctrl.abort(), timeout);
  const res = await fetch(layaUrl(cfg) + '/decide', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', ...authHeaders(cfg) },
    signal: ctrl.signal,
    body: JSON.stringify(payload),
  }).finally(() => clearTimeout(t));
  if (!res.ok) {
    const body = await res.text().catch(() => '');
    throw new Error(`Laya error ${res.status}: ${body.slice(0, 300)}`);
  }
  const data = await res.json();
  if (!data || !data.answers) throw new Error('Empty Laya decide response');
  return data;
}

// Probability that a noul answer is "yes" (true/1 option).
function probOf(answer, yesLabel = true) {
  if (!answer) return 0.5;
  const probs = answer.probs || {};
  if (probs && Object.keys(probs).length) {
    for (const [k, v] of Object.entries(probs)) {
      if (String(k).toLowerCase() === String(yesLabel).toLowerCase()) return Number(v) || 0.5;
    }
    if (typeof yesLabel === 'boolean') {
      // binary: the "yes"/"true" key is whatever is not the false key
      for (const [k, v] of Object.entries(probs)) {
        if (!/^(no|false|0)$/i.test(String(k))) return Number(v) || 0.5;
      }
    }
    return Number(Object.values(probs)[0]) || 0.5;
  }
  if (answer.noul !== undefined && answer.noul !== null) return Number(answer.noul) || 0.5;
  return 0.5;
}

// Model-reported confidence (top probability or raw confidence field).
function confidenceOf(answer) {
  if (!answer) return 0.5;
  const c = Number(answer.confidence);
  if (!Number.isNaN(c) && c > 0) return c;
  const probs = answer.probs || {};
  const vals = Object.values(probs).map(Number).filter(v => !Number.isNaN(v));
  if (vals.length) return Math.max(...vals);
  const p = Number(answer.noul);
  if (!Number.isNaN(p)) return Math.max(p, 1 - p);
  return 0.5;
}

// Default confidence gate: below this we fall back to the LLM brain.
const DEFAULT_CONF_GATE = 0.7;

async function layaVerify(original, rewritten, opts = {}) {
  try {
    if (!(await isLayaReachable())) return { used: false, ok: true, issues: [], fidelity: null, confidence: 0 };
    const state =
      'ORIGINAL:\n' + truncateForState(original, 1400) + '\n---\nREWRITTEN:\n' + truncateForState(rewritten, 1400);
    const data = await layaDecide(state, VERIFY_QUESTIONS, opts);
    const a = data.answers || {};
    const faithful = probOf(a.faithful);
    const halluc = probOf(a.hallucination);
    const meta = probOf(a.meta);
    const confidence = Math.min(confidenceOf(a.faithful), confidenceOf(a.hallucination), confidenceOf(a.meta));
    const ok = faithful >= 0.5 && halluc < 0.5 && meta < 0.5;
    const issues = [];
    if (faithful < 0.5) issues.push('Laya: rewrite drifts from original meaning');
    if (halluc >= 0.5) issues.push('Laya: possible invented facts present');
    if (meta >= 0.5) issues.push('Laya: meta-text / non-prose content present');
    console.error(`  [laya] verify → ok=${ok}, faithful=${faithful.toFixed(2)}, halluc=${halluc.toFixed(2)}, meta=${meta.toFixed(2)}, conf=${confidence.toFixed(2)}`);
    return { used: true, ok, issues, fidelity: Math.round(faithful * 100), confidence };
  } catch (e) {
    console.error(`  [laya] verify failed, falling back to LLM brain: ${e.message}`);
    return { used: false, ok: true, issues: [], fidelity: null, confidence: 0 };
  }
}

async function layaHumanScore(text, opts = {}) {
  try {
    if (!(await isLayaReachable())) return null;
    const data = await layaDecide(truncateForState(text, 1400), JUDGE_QUESTION, opts);
    const ans = (data.answers || {}).human;
    const p = probOf(ans);
    const confidence = confidenceOf(ans);
    console.error(`  [laya] judge → human=${Math.round(p * 100)}, conf=${confidence.toFixed(2)}`);
    return { human_score: Math.round(p * 100), confidence, notes: 'laya' };
  } catch (e) {
    console.error(`  [laya] judge failed, falling back to LLM brain: ${e.message}`);
    return null;
  }
}

// Whole-document humanness via N windows (Laya budget ~320-768 tokens per call).
// Windows are weighted equally; confidence = min across windows.
const WINDOW_CHARS = 1200;
const MAX_WINDOWS = 4;

async function layaHumanWinScore(text, opts = {}) {
  try {
    if (!(await isLayaReachable())) return null;
    text = String(text || '').trim();
    if (!text) return null;
    const parts = [];
    for (let i = 0; i < text.length && parts.length < MAX_WINDOWS; i += WINDOW_CHARS) {
      parts.push(text.slice(i, i + WINDOW_CHARS));
    }
    let sum = 0;
    let minConf = 1;
    for (const part of parts) {
      const data = await layaDecide(part, JUDGE_QUESTION, opts);
      const ans = (data.answers || {}).human;
      const p = probOf(ans);
      const c = confidenceOf(ans);
      sum += p;
      minConf = Math.min(minConf, c);
    }
    const p = sum / parts.length;
    console.error(`  [laya] win-judge → human=${Math.round(p * 100)} (${parts.length} windows), conf=${minConf.toFixed(2)}`);
    return { human_score: Math.round(p * 100), confidence: minConf, windows: parts.length, notes: 'laya-windows' };
  } catch (e) {
    console.error(`  [laya] win-judge failed, falling back to LLM eval: ${e.message}`);
    return null;
  }
}

// Decision check for Pass 3 backfire: did the alternrewrite actually improve naturalness?
async function layaBackfireCheck(before, after, opts = {}) {
  try {
    if (!(await isLayaReachable())) return null;
    const state =
      'PREVIOUS VERSION:\n' + truncateForState(before, 1400) + '\n---\nREWRITTEN:\n' + truncateForState(after, 1400);
    const data = await layaDecide(state, BACKFIRE_QUESTION, opts);
    const ans = (data.answers || {}).improvement;
    return { improved: probOf(ans) >= 0.5, confidence: confidenceOf(ans) };
  } catch (e) {
    console.error(`  [laya] backfire check failed: ${e.message}`);
    return null;
  }
}

